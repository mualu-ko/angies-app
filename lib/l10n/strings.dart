  static String get(String lang, String key, [Map<String, Object> args = const {}]) {
    var s = (lang == 'sw' ? _sw[key] : null) ?? _en[key] ?? key;
    args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }
